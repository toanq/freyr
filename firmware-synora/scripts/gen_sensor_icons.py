#!/usr/bin/env python3
"""Generates the dashboard tile icons + ping-screen bell (main/boards/synora/
sensor_icons.{h,cc}) from the SVGs in svgs/ (repo root) -- same "checked-in
script generates a binary asset, do not hand-edit" convention as
gen_font.py/gen_logo.py.

Each SVG is rasterized with cairosvg (stroke-based outline icons -- plain
ImageMagick/MSVG doesn't render stroke-only paths) then thresholded to a
1bpp mask, same packing as text_renderer.h's GlyphBitmap/qr_download.h/
logo_icon.h: MSB-first, each row byte-padded. BlitMonoBitmap blits each in
whatever color the caller passes at draw time.

Usage:
    python3 gen_sensor_icons.py
"""
import pathlib

import cairosvg
from PIL import Image

SVG_DIR = pathlib.Path(__file__).resolve().parent.parent.parent / "svgs"
OUTPUT_DIR = pathlib.Path(__file__).resolve().parent.parent / "main" / "boards" / "synora"

INK_THRESHOLD = 160

# (constant name, svg filename, pixel size) -- all source SVGs are square
# (24x24 viewBox), so size is a single edge length.
ICONS = [
    ("Temperature", "temperature-half-svgrepo-com.svg", 26),  # dashboard tile: temperature
    ("Humidity", "wind-svgrepo-com.svg", 26),                 # dashboard tile: humidity
    ("SoilMoisture", "water-drop-svgrepo-com.svg", 26),       # dashboard tile: soil moisture
    ("WaterLevel", "wave-svgrepo-com.svg", 26),               # dashboard tile: water level
    ("Bell", "bell-ring.svg", 80),                            # ping ("find my device") screen hero
]


def to_1bpp_bitmap(png_bytes, size):
    import io

    gray = Image.open(io.BytesIO(png_bytes)).convert("L")
    pixels = gray.load()
    row_bytes = (size + 7) // 8
    bitmap = bytearray(row_bytes * size)
    for y in range(size):
        for x in range(size):
            if pixels[x, y] < INK_THRESHOLD:
                bitmap[y * row_bytes + x // 8] |= 0x80 >> (x % 8)
    return bytes(bitmap)


def main():
    header = OUTPUT_DIR / "sensor_icons.h"
    source = OUTPUT_DIR / "sensor_icons.cc"

    with header.open("w") as h, source.open("w") as c:
        h.write("// GENERATED by scripts/gen_sensor_icons.py -- do not hand-edit.\n")
        h.write("// Dashboard tile icons + ping-screen bell, thresholded from svgs/*.svg.\n")
        h.write("#pragma once\n\n#include <cstdint>\n#include <cstddef>\n\n")

        c.write("// GENERATED by scripts/gen_sensor_icons.py -- do not hand-edit.\n")
        c.write('#include "sensor_icons.h"\n\n')

        for name, filename, size in ICONS:
            png_bytes = cairosvg.svg2png(
                url=str(SVG_DIR / filename), output_width=size, output_height=size,
                background_color="white")
            bitmap = to_1bpp_bitmap(png_bytes, size)

            h.write(f"extern const uint8_t kIcon{name}Bitmap[];\n")
            h.write(f"constexpr int kIcon{name}Size = {size};\n\n")

            bytes_str = ", ".join(f"0x{b:02X}" for b in bitmap)
            c.write(f"const uint8_t kIcon{name}Bitmap[] = {{{bytes_str}}};\n")
            print(f"{name}: {filename} -> {size}x{size}, {len(bitmap)} bytes")

    print(f"Wrote {header} and {source}")


if __name__ == "__main__":
    main()
