#!/usr/bin/env python3
"""Generates the dashboard header's WiFi + mute status icons (main/boards/
synora/status_icons.{h,cc}) from the SVGs in svgs/ (repo root) -- same
"checked-in script generates a binary asset, do not hand-edit" convention as
gen_sensor_icons.py/gen_font.py/gen_logo.py.

Unlike the sensor tile icons (one glyph per reading, tinted by status color
but never swapped), the WiFi icon swaps to a different source SVG per
TileStatus (plain arcs/exclamation/slash) and the mute icon swaps between two
source SVGs per boolean state -- picking the glyph that actually matches the
state, not just recoloring one shape.

Usage:
    python3 gen_status_icons.py
"""
import pathlib

import cairosvg
from PIL import Image

SVG_DIR = pathlib.Path(__file__).resolve().parent.parent.parent / "svgs"
OUTPUT_DIR = pathlib.Path(__file__).resolve().parent.parent / "main" / "boards" / "synora"

INK_THRESHOLD = 160

# (constant name, svg filename, pixel size) -- all source SVGs are square
# (24x24 viewBox), so size is a single edge length.
ICONS = [
    ("WifiGood", "wifi-svgrepo-com.svg", 18),              # header: WiFi connected
    ("WifiWarn", "wifi-exclamation-svgrepo-com.svg", 18),   # header: WiFi scanning/connecting
    ("WifiBad", "wifi-slash-svgrepo-com.svg", 18),          # header: WiFi disconnected
    ("SpeakerUnmuted", "speaker-2-svgrepo-com.svg", 18),    # header: mic/speaker live
    ("SpeakerMuted", "speaker-cross-svgrepo-com.svg", 18),  # header: mic/speaker muted
]


def to_1bpp_bitmap(png_bytes, size):
    import io

    gray = Image.open(io.BytesIO(png_bytes)).convert("L")
    pixels = gray.load()
    row_bytes = (size + 7) // 8
    bitmap = bytearray(row_bytes * size)
    for y in range(size):
        for x in range(size):
            if pixels[x, y] < INK_THRESHOLD:
                bitmap[y * row_bytes + x // 8] |= 0x80 >> (x % 8)
    return bytes(bitmap)


def main():
    header = OUTPUT_DIR / "status_icons.h"
    source = OUTPUT_DIR / "status_icons.cc"

    with header.open("w") as h, source.open("w") as c:
        h.write("// GENERATED by scripts/gen_status_icons.py -- do not hand-edit.\n")
        h.write("// Dashboard header WiFi/mute icons, thresholded from svgs/*.svg.\n")
        h.write("#pragma once\n\n#include <cstdint>\n#include <cstddef>\n\n")

        c.write("// GENERATED by scripts/gen_status_icons.py -- do not hand-edit.\n")
        c.write('#include "status_icons.h"\n\n')

        for name, filename, size in ICONS:
            png_bytes = cairosvg.svg2png(
                url=str(SVG_DIR / filename), output_width=size, output_height=size,
                background_color="white")
            bitmap = to_1bpp_bitmap(png_bytes, size)

            h.write(f"extern const uint8_t kIcon{name}Bitmap[];\n")
            h.write(f"constexpr int kIcon{name}Size = {size};\n\n")

            bytes_str = ", ".join(f"0x{b:02X}" for b in bitmap)
            c.write(f"const uint8_t kIcon{name}Bitmap[] = {{{bytes_str}}};\n")
            print(f"{name}: {filename} -> {size}x{size}, {len(bitmap)} bytes")

    print(f"Wrote {header} and {source}")


if __name__ == "__main__":
    main()
