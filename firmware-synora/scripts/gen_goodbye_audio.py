#!/usr/bin/env python3
"""Generates the end-of-conversation goodbye-clip PCM asset (main/boards/
synora/goodbye_audio.{h,cc}) -- same TTS-sidecar-via-docker-exec approach as
gen_welcome_audio.py (see that file's docstring for why), just a different
checked-in asset: SynoraVoiceSession::PlayGoodbye() plays this straight to
the speaker (no server round trip) when a relistened turn times out with no
speech, ending the conversation gracefully instead of silently going idle.

Usage:
    python3 gen_goodbye_audio.py "Tạm biệt, hẹn gặp lại bạn nhé!" ["Thùy Dung"]
"""
import json
import pathlib
import subprocess
import sys
import wave
import io
import struct

OUTPUT_DIR = pathlib.Path(__file__).resolve().parent.parent / "main" / "boards" / "synora"
CONTAINER = "synora-tts-1"


def synthesize(text: str, voice: str | None) -> bytes:
    """Returns raw int16 PCM bytes at 16kHz mono (the TTS service's own
    output format, already matched to the firmware's fixed sample rate)."""
    payload = {"text": text}
    if voice:
        payload["voice"] = voice
    script = f"""
import urllib.request, json
data = json.dumps({json.dumps(payload)}).encode()
req = urllib.request.Request("http://localhost:8000/synthesize", data=data, headers={{"Content-Type": "application/json"}})
resp = urllib.request.urlopen(req, timeout=60)
import sys
sys.stdout.buffer.write(resp.read())
"""
    result = subprocess.run(
        ["docker", "exec", "-i", CONTAINER, "python3", "-c", script],
        capture_output=True, check=True,
    )
    with wave.open(io.BytesIO(result.stdout), "rb") as w:
        assert w.getnchannels() == 1 and w.getsampwidth() == 2, "expected mono 16-bit PCM"
        return w.readframes(w.getnframes())


def normalize(samples: list[int], target_peak: int = 32000) -> list[int]:
    """Scales samples so the loudest one hits target_peak (just under int16's
    32767 ceiling, leaving a little headroom against rounding) -- see
    gen_welcome_audio.py's normalize() for why this is needed (output_volume_
    is already maxed at runtime, so sample-level gain is the only remaining
    lever)."""
    peak = max(abs(s) for s in samples) if samples else 0
    if peak == 0:
        return samples
    gain = target_peak / peak
    return [max(-32768, min(32767, round(s * gain))) for s in samples]


def main():
    if len(sys.argv) not in (2, 3):
        print(f"Usage: {sys.argv[0]} <text> [voice]", file=sys.stderr)
        sys.exit(1)
    text = sys.argv[1]
    voice = sys.argv[2] if len(sys.argv) == 3 else None

    pcm = synthesize(text, voice)
    samples = len(pcm) // 2
    raw_samples = struct.unpack(f"<{samples}h", pcm)
    boosted = normalize(list(raw_samples))
    values = ",".join(str(v) for v in boosted)

    header = OUTPUT_DIR / "goodbye_audio.h"
    header.write_text(
        "#pragma once\n\n"
        "// GENERATED by scripts/gen_goodbye_audio.py -- do not hand-edit.\n"
        "#include <cstddef>\n"
        "#include <cstdint>\n\n"
        "extern const int16_t kGoodbyeAudioPcm[];\n"
        "extern const size_t kGoodbyeAudioSampleCount;\n"
    )
    source = OUTPUT_DIR / "goodbye_audio.cc"
    source.write_text(
        "// GENERATED by scripts/gen_goodbye_audio.py -- do not hand-edit.\n"
        '#include "goodbye_audio.h"\n\n'
        f"const int16_t kGoodbyeAudioPcm[] = {{{values}}};\n"
        f"const size_t kGoodbyeAudioSampleCount = {samples};\n"
    )
    print(f"Wrote {samples} samples ({samples / 16000:.2f}s) to {source}")


if __name__ == "__main__":
    main()
