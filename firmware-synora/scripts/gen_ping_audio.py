#!/usr/bin/env python3
"""Generates the "find my pot" ping-chime PCM asset (main/boards/synora/
ping_audio.{h,cc}) -- same "checked-in script generates a binary asset, do
not hand-edit" convention as gen_welcome_audio.py/gen_font.py.

Unlike gen_welcome_audio.py this doesn't call the TTS sidecar -- self.
find_device needs an audible "here I am" cue, not spoken words, so it's a
synthesized two-harmonic decaying tone (classic bell/chime shape: a
fundamental plus a detuned upper partial, both decaying exponentially)
rather than a recorded/synthesized voice clip.

Usage:
    python3 gen_ping_audio.py
"""
import math
import pathlib

OUTPUT_DIR = pathlib.Path(__file__).resolve().parent.parent / "main" / "boards" / "synora"
SAMPLE_RATE = 16000  # matches config.h's AUDIO_OUTPUT_SAMPLE_RATE

# A5 fundamental + a detuned-and-quieter upper partial for a bit of
# bell-like shimmer, both decaying exponentially rather than cutting off
# abruptly -- an abrupt stop reads as a click/pop, not a chime.
FUNDAMENTAL_HZ = 880.0
PARTIAL_HZ = 880.0 * 2.76  # inharmonic on purpose -- real bells aren't pure octaves
PARTIAL_GAIN = 0.35
DURATION_S = 0.9
DECAY_RATE = 5.5  # higher = faster decay
TARGET_PEAK = 32000  # just under int16 ceiling, same headroom reasoning as gen_welcome_audio.py


def main():
    n_samples = int(SAMPLE_RATE * DURATION_S)
    samples = []
    for i in range(n_samples):
        t = i / SAMPLE_RATE
        envelope = math.exp(-DECAY_RATE * t)
        value = math.sin(2 * math.pi * FUNDAMENTAL_HZ * t) + PARTIAL_GAIN * math.sin(2 * math.pi * PARTIAL_HZ * t)
        samples.append(value * envelope)

    peak = max(abs(s) for s in samples)
    gain = TARGET_PEAK / peak
    pcm = [max(-32768, min(32767, round(s * gain))) for s in samples]
    values = ",".join(str(v) for v in pcm)

    header = OUTPUT_DIR / "ping_audio.h"
    header.write_text(
        "#pragma once\n\n"
        "// GENERATED by scripts/gen_ping_audio.py -- do not hand-edit.\n"
        "#include <cstddef>\n"
        "#include <cstdint>\n\n"
        "extern const int16_t kPingAudioPcm[];\n"
        "extern const size_t kPingAudioSampleCount;\n"
    )
    source = OUTPUT_DIR / "ping_audio.cc"
    source.write_text(
        "// GENERATED by scripts/gen_ping_audio.py -- do not hand-edit.\n"
        '#include "ping_audio.h"\n\n'
        f"const int16_t kPingAudioPcm[] = {{{values}}};\n"
        f"const size_t kPingAudioSampleCount = {len(pcm)};\n"
    )
    print(f"Wrote {len(pcm)} samples ({len(pcm) / SAMPLE_RATE:.2f}s) to {source}")


if __name__ == "__main__":
    main()
