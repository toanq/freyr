#!/usr/bin/env python3
"""Generates the TFT header's brand-mark bitmap (main/boards/synora/logo_icon.{h,cc})
from the project's logo.svg -- same "checked-in script generates a binary asset,
do not hand-edit" convention as gen_font.py's font tables/QR bitmap.

logo.svg (repo root) isn't a real vector logo -- it's a single embedded raster
<image> (base64 PNG) inside an SVG wrapper -- so this extracts that PNG
directly rather than rasterizing SVG paths. The source art is black line-art
on a white background; this thresholds it to a 1bpp mask (matching
text_renderer.h's GlyphBitmap/qr_download.h's packing: MSB-first, each row
byte-padded) at a small fixed size for the dashboard header, where
BlitMonoBitmap blits it in whatever color the caller passes (green, to match
the dashboard's kTileColorGood accent -- see synora_display.cc).

Usage:
    python3 gen_logo.py
"""
import base64
import pathlib

from PIL import Image

LOGO_SVG = pathlib.Path(__file__).resolve().parent.parent.parent / "logo.svg"
OUTPUT_DIR = pathlib.Path(__file__).resolve().parent.parent / "main" / "boards" / "synora"

# Header icon size -- small enough to sit next to the 24px "SYNORA" title
# within the header's ~38px vertical band, matching the source art's ~0.8
# width:height aspect ratio (296.86 x 370.95).
ICON_WIDTH = 22
ICON_HEIGHT = 28

# Boot splash size -- same aspect ratio, big enough to read as a real logo
# centered on the 240x400 panel with room to spare on every side.
BOOT_WIDTH = 140
BOOT_HEIGHT = 175

# Luminance threshold (0-255) below which a (downsampled, anti-aliased)
# pixel counts as "ink" -- picked so the logo's line strokes stay a
# connected/legible shape at this small size rather than fragmenting.
INK_THRESHOLD = 160


def extract_embedded_png():
    content = LOGO_SVG.read_bytes()
    start = content.find(b"base64,") + len(b"base64,")
    end = content.find(b'"', start)
    raw = content[start:end].replace(b"&#10;", b"").replace(b"&#13;", b"")
    return Image.open(__import__("io").BytesIO(base64.b64decode(raw)))


def to_1bpp_bitmap(img, width, height):
    gray = img.convert("L").resize((width, height), Image.LANCZOS)
    pixels = gray.load()
    row_bytes = (width + 7) // 8
    bitmap = bytearray(row_bytes * height)
    for y in range(height):
        for x in range(width):
            if pixels[x, y] < INK_THRESHOLD:
                bitmap[y * row_bytes + x // 8] |= 0x80 >> (x % 8)
    return bytes(bitmap)


def write_files(icon_bitmap, boot_bitmap):
    header = OUTPUT_DIR / "logo_icon.h"
    source = OUTPUT_DIR / "logo_icon.cc"

    with header.open("w") as out:
        out.write("// GENERATED by scripts/gen_logo.py -- do not hand-edit.\n")
        out.write("// Synora brand-mark, thresholded from logo.svg's embedded PNG --\n")
        out.write("// a small header icon and a bigger boot-splash version.\n")
        out.write("#pragma once\n\n#include <cstdint>\n#include <cstddef>\n\n")
        out.write("extern const uint8_t kLogoIconBitmap[];\n")
        out.write(f"constexpr int kLogoIconWidth = {ICON_WIDTH};\n")
        out.write(f"constexpr int kLogoIconHeight = {ICON_HEIGHT};\n\n")
        out.write("extern const uint8_t kBootLogoBitmap[];\n")
        out.write(f"constexpr int kBootLogoWidth = {BOOT_WIDTH};\n")
        out.write(f"constexpr int kBootLogoHeight = {BOOT_HEIGHT};\n")

    with source.open("w") as out:
        out.write("// GENERATED by scripts/gen_logo.py -- do not hand-edit.\n")
        out.write('#include "logo_icon.h"\n\n')
        icon_bytes_str = ", ".join(f"0x{b:02X}" for b in icon_bitmap)
        out.write(f"const uint8_t kLogoIconBitmap[] = {{{icon_bytes_str}}};\n")
        boot_bytes_str = ", ".join(f"0x{b:02X}" for b in boot_bitmap)
        out.write(f"const uint8_t kBootLogoBitmap[] = {{{boot_bytes_str}}};\n")

    print(f"Wrote {header} and {source}")
    print(f"  icon: {ICON_WIDTH}x{ICON_HEIGHT}, {len(icon_bitmap)} bytes")
    print(f"  boot: {BOOT_WIDTH}x{BOOT_HEIGHT}, {len(boot_bitmap)} bytes")


def main():
    img = extract_embedded_png()
    icon_bitmap = to_1bpp_bitmap(img, ICON_WIDTH, ICON_HEIGHT)
    boot_bitmap = to_1bpp_bitmap(img, BOOT_WIDTH, BOOT_HEIGHT)
    write_files(icon_bitmap, boot_bitmap)


if __name__ == "__main__":
    main()
