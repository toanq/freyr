#!/usr/bin/env python3
"""Generates a boot-time welcome-chime PCM asset (main/boards/synora/
welcome_audio.{h,cc}) by calling the TTS sidecar's /synthesize endpoint --
same "checked-in script generates a binary asset, do not hand-edit"
convention as gen_status_icons.py/gen_logo.py.

This is a hardware-diagnostic tool, not a permanent voice-pipeline feature:
it lets main.cc play a known-good clip straight to the speaker at boot,
bypassing the whole MQTT/STT/LLM/TTS round trip, to isolate whether garbled/
static audio is a wiring problem or a software one.

The TTS container has no host-published port in this project's
docker-compose.yml, so this shells out to `docker exec` rather than hitting
localhost directly -- run this from a host that can reach the running
`synora-tts-1` container.

Usage:
    python3 gen_welcome_audio.py "Xin chào bạn của tôi" ["Thùy Dung"]
"""
import json
import pathlib
import subprocess
import sys
import wave
import io

OUTPUT_DIR = pathlib.Path(__file__).resolve().parent.parent / "main" / "boards" / "synora"
CONTAINER = "synora-tts-1"


def synthesize(text: str, voice: str | None) -> bytes:
    """Returns raw int16 PCM bytes at 16kHz mono (the TTS service's own
    output format, already matched to the firmware's fixed sample rate)."""
    payload = {"text": text}
    if voice:
        payload["voice"] = voice
    script = f"""
import urllib.request, json
data = json.dumps({json.dumps(payload)}).encode()
req = urllib.request.Request("http://localhost:8000/synthesize", data=data, headers={{"Content-Type": "application/json"}})
resp = urllib.request.urlopen(req, timeout=60)
import sys
sys.stdout.buffer.write(resp.read())
"""
    result = subprocess.run(
        ["docker", "exec", "-i", CONTAINER, "python3", "-c", script],
        capture_output=True, check=True,
    )
    with wave.open(io.BytesIO(result.stdout), "rb") as w:
        assert w.getnchannels() == 1 and w.getsampwidth() == 2, "expected mono 16-bit PCM"
        return w.readframes(w.getnframes())


def normalize(samples: list[int], target_peak: int = 32000) -> list[int]:
    """Scales samples so the loudest one hits target_peak (just under int16's
    32767 ceiling, leaving a little headroom against rounding) -- the TTS
    service's own output otherwise leaves real peak headroom unused, and
    output_volume_ is already maxed (see main.cc's SetOutputVolume(100)), so
    the only remaining way to make this clip louder is boosting the samples
    themselves."""
    peak = max(abs(s) for s in samples) if samples else 0
    if peak == 0:
        return samples
    gain = target_peak / peak
    return [max(-32768, min(32767, round(s * gain))) for s in samples]


def main():
    if len(sys.argv) not in (2, 3):
        print(f"Usage: {sys.argv[0]} <text> [voice]", file=sys.stderr)
        sys.exit(1)
    text = sys.argv[1]
    voice = sys.argv[2] if len(sys.argv) == 3 else None

    pcm = synthesize(text, voice)
    samples = len(pcm) // 2
    raw_samples = __import__("struct").unpack(f"<{samples}h", pcm)
    boosted = normalize(list(raw_samples))
    values = ",".join(str(v) for v in boosted)

    header = OUTPUT_DIR / "welcome_audio.h"
    header.write_text(
        "#pragma once\n\n"
        "// GENERATED by scripts/gen_welcome_audio.py -- do not hand-edit.\n"
        "#include <cstddef>\n"
        "#include <cstdint>\n\n"
        "extern const int16_t kWelcomeAudioPcm[];\n"
        "extern const size_t kWelcomeAudioSampleCount;\n"
    )
    source = OUTPUT_DIR / "welcome_audio.cc"
    source.write_text(
        "// GENERATED by scripts/gen_welcome_audio.py -- do not hand-edit.\n"
        '#include "welcome_audio.h"\n\n'
        f"const int16_t kWelcomeAudioPcm[] = {{{values}}};\n"
        f"const size_t kWelcomeAudioSampleCount = {samples};\n"
    )
    print(f"Wrote {samples} samples ({samples / 16000:.2f}s) to {source}")


if __name__ == "__main__":
    main()
